DEC_NAMES = {"eir_found_scriptorium_decision": "Found a Great Scriptorium", "eir_compile_brehon_laws_decision": "Compile the Brehon Laws",
             "eir_found_bardic_schools_decision": "Charter the Schools of the Filí"}


def build():
    L = Loc("eir_culture_l_english.yml")
    out = ["# Eire Reborn - culture innovations. Generated by tools/gen_culture.py\n\n#### Local types ####\n"]
    for name, fn in ICONS.items():
        out.append('@%s = "gfx/interface/icons/culture_innovations/%s.dds"\n' % (name, fn))
    out.append("\n")
    L.section("culture innovations")
    for key, skill, group, era, icon, name, desc, mods, unlocks in INNOVATIONS:
        k = "innovation_eir_" + key
        check_keys(k, mods)
        out.append(f"""{k} = {{
	skill = {skill}
	group = culture_group_{group}
	culture_era = culture_era_{era}
	region = world_europe_west_britannia
	icon = @{icon}

	potential = {{
		OR = {{
			has_cultural_pillar = heritage_goidelic
			has_cultural_pillar = heritage_brythonic
		}}
	}}

	character_modifier = {{
{fields_block(mods, chr(9) * 2)}	}}
""")
        for u in unlocks:
            if u.startswith("unlock_decision = "):
                # the game's own scripts never use unlock_decision, so a plain description line is used instead
                dkey = u.split("= ")[1]
                out.append("\tcustom = eir_innov_unlock_%s\n" % dkey)
                L.add("eir_innov_unlock_%s" % dkey, "Helps unlock the decision %s" % DEC_NAMES[dkey])
            else:
                out.append("\t%s\n" % u)
        out.append(f"""
	ai_weight_for_fascination = {{
		value = 50
	}}
}}

""")
        L.add(k, name)
        L.add(k + "_desc", desc)
    write("common/culture/innovations/eir_innovations.txt", "".join(out))
    L.write()
    print("culture innovations written (%d)" % len(INNOVATIONS))


if __name__ == "__main__":
    build()
