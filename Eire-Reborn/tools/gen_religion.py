# god roles: (loc key prefix in the localization block, god name, she/he token, her/his token, her/him token, possessive)
GODS = [
    ("HighGod", "the Dagda", "HE", "HIS", "HIM"),
    ("Creator", "Danu", "SHE", "HER", "HER"),
    ("HealthGod", "Dian Cécht", "HE", "HIS", "HIM"),
    ("FertilityGod", "Brigid", "SHE", "HER", "HER"),
    ("WarGod", "the Morrígan", "SHE", "HER", "HER"),
    ("KnowledgeGod", "Ogma", "HE", "HIS", "HIM"),
    ("WaterGod", "Manannán", "HE", "HIS", "HIM"),
    ("NightGod", "the Cailleach", "SHE", "HER", "HER"),
]

PRIEST_TERMS = {
    "PriestMale": ("Druid", "Druids"), "PriestFemale": ("Druidess", "Druidesses"), "PriestNeuter": ("Druid", "Druids"),
    "HouseOfWorship": ("grove", None), "ReligiousText": ("the Triads", None),
}


def build():
    L = Loc("eir_religion_l_english.yml")
    # ------------------------------------------------------------------ holy sites
    out = ["# Eire Reborn - holy sites. Generated by tools/gen_religion.py\n\n"]
    L.section("holy sites")
    for key, county, barony, name, eff, fm, hm in SITES:
        check_keys(key, fm)
        check_keys(key, hm)
        out.append(f"""{key} = {{
	county = {county}
	barony = {barony}

	county_holder_character_modifier = {{
{fields_block(hm, chr(9) * 2)}	}}

	faith_character_modifier = {{
{fields_block(fm, chr(9) * 2)}	}}
}}

""")
        L.add("holy_site_%s_name" % key, name)
        L.add("holy_site_%s_effects" % key, eff)
    write("common/religion/holy_site_types/eir_holy_sites.txt", "".join(out))

    # ------------------------------------------------------------------ the Druidic faith
    loc_lines = ""
    for pre, god, she, her, him in GODS:
        base = "eir_druidic_" + pre.lower()
        if pre == "HighGod":
            # the High God block has its own key names in the religion localization
            loc_lines += f"""		HighGodName = {base}_name
		HighGodName2 = {base}_name
		HighGodNamePossessive = {base}_name_possessive
		HighGodNameSheHe = CHARACTER_SHEHE_{she}
		HighGodHerselfHimself = CHARACTER_HIMSELF
		HighGodHerHis = CHARACTER_HERHIS_{her}
"""
        else:
            loc_lines += f"""		{pre}Name = {base}_name
		{pre}NamePossessive = {base}_name_possessive
		{pre}SheHe = CHARACTER_SHEHE_{she}
		{pre}HerHis = CHARACTER_HERHIS_{her}
		{pre}HerHim = CHARACTER_HERHIM_{him}
"""
        L.add(base + "_name", god)
        L.add(base + "_name_possessive", god + "'s" if not god.endswith("s") else god + "'")
    loc_lines += """		PriestMale = eir_druidic_priest
		PriestMalePlural = eir_druidic_priest_plural
		PriestFemale = eir_druidic_priestess
		PriestFemalePlural = eir_druidic_priestess_plural
		PriestNeuter = eir_druidic_priest
		PriestNeuterPlural = eir_druidic_priest_plural
		HouseOfWorship = eir_druidic_house_of_worship
		HouseOfWorship2 = eir_druidic_house_of_worship_2
		HouseOfWorship3 = eir_druidic_house_of_worship_3
		HouseOfWorshipPlural = eir_druidic_house_of_worship_plural
		ReligiousText = eir_druidic_religious_text
		ReligiousText2 = eir_druidic_religious_text_2
		ReligiousText3 = eir_druidic_religious_text_3
"""
    for k, v in (("priest", "Druid"), ("priest_plural", "Druids"), ("priestess", "Druidess"), ("priestess_plural", "Druidesses"),
                 ("house_of_worship", "grove"), ("house_of_worship_2", "nemeton"), ("house_of_worship_3", "sacred oak"), ("house_of_worship_plural", "groves"),
                 ("religious_text", "the Triads"), ("religious_text_2", "the Tales"), ("religious_text_3", "the Lore")):
        L.add("eir_druidic_" + k, v)
    faith = f"""eir_druidic = {{
	faith_details = {{
		religion = paganism_religion
		color = {{ 0.18 0.5 0.25 }}
		icon = pagan
		reformed_icon = pagan_reformed
	}}

	eminent_holy_sites = {{
		eir_tara
		eir_uisneach
		eir_cruachan
	}}

	holy_sites = {{
		eir_newgrange
		eir_emain_macha
		eir_croagh_patrick
		eir_armagh
		eir_cashel
	}}

	tenets = {{
		tenet_sanctity_of_nature
		tenet_ancestor_worship
		tenet_megaliths
	}}

	doctrines = {{
		unreformed_faith_doctrine
	}}

	localization = {{
{loc_lines}	}}
}}
"""
    L.section("the Druidic faith")
    L.add("eir_druidic", "Druidry")
    L.add("eir_druidic_adj", "Druidic")
    L.add("eir_druidic_adherent", "Druid")
    L.add("eir_druidic_adherent_plural", "Druids")
    L.add("eir_druidic_desc", "The old faith of the oak-groves: the quarter-day fires, the judges and the poets, and the belief that the island itself is holy. The druids kept it alive in secret under the monks; now a king has lit the fires in public.")
    write("common/religion/faith_types/eir_faith_types.txt", "# Eire Reborn - faiths. Generated by tools/gen_religion.py\n\n" + faith)
    write("history/faiths/eir_faiths.txt", """# Eire Reborn - faith history. Generated by tools/gen_religion.py
# The Druidic faith must be flagged as created or the game will not let anyone convert to it.
eir_druidic = {
	867.1.1 = {
		created = yes
		known = {
			tenet_sanctity_of_nature
			tenet_ancestor_worship
			tenet_megaliths
		}
	}
}
""")

    # ------------------------------------------------------------------ the Culdee Reform (a rite of the Christian faith, made when the ruler decides)
    rites = ""
    L.section("the Culdee Reform")
    for rkey, parent in (("eir_culdee_rite", "christian_faith"), ("eir_culdee_rite_catholic", "catholic")):
        rites += f"""{rkey} = {{
	name = {rkey}
	desc = {rkey}_desc
	faith = {parent}
	create = no

	color = {{ 0.45 0.62 0.38 }}
	icon = christianity_celtic_cross_tall_02

	tenets = {{
		tenet_vows_of_poverty
		tenet_communal_identity
		tenet_asceticism
	}}

	doctrines = {{
		special_doctrine_is_western_christian_faith
		doctrine_pluralism_pluralistic
		doctrine_divorce_approval
		doctrine_kinslaying_any_dynasty_member_crime
		doctrine_clerical_function_alms_and_pacification
		doctrine_clerical_succession_spiritual_fixed_appointment
		doctrine_clerical_marriage_allowed
		doctrine_funeral_bewailment
		doctrine_anointment_permitted
		doctrine_monasticism_encouraged
	}}
}}

"""
        L.add(rkey, "Culdee Reform")
        L.add(rkey + "_adj", "Culdee")
        L.add(rkey + "_adherent", "Culdee")
        L.add(rkey + "_adherent_plural", "Culdees")
        L.add(rkey + "_desc", "The reform of the hermit-monks: a Church of small communities, poor abbots, married priests and long pilgrimages, in which the saint's grave matters more than the bishop's seat.")
    write("common/religion/rite_types/eir_rite_types.txt", "# Eire Reborn - rites. Generated by tools/gen_religion.py\n\n" + rites)
    L.write()
    print("religion written (%d holy sites, 1 faith, 2 rites)" % len(SITES))


if __name__ == "__main__":
    build()
