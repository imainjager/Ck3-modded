"""Update 10: three Celtic siege weapons. Writes:
  common/men_at_arms_types/eir_siege_types.txt     Fire-Brands, Wall-Hook and Ladder Crews, Hide-Covered Rams
  common/script_values/eir_siege_values.txt         their costs (a share of the base game's own onager, mangonel and trebuchet costs)
  localization/english/eir_siege_l_english.yml
Every field used here is one the base game's own siege weapons use: type siege_weapon, fights_in_main_phase = no, damage 0, toughness, siege_tier,
siege_value, stack, costs, provision_cost, can_recruit, allowed_in_hired_troops, icon, and holding_bonus with siege_value (the base game's
Mandala MAA use that). Siege weapons cannot have terrain bonuses or counters (they do not fight in the main phase), so the special effects are holding bonuses."""
from eir_lib import *

UNITS = [
    dict(key="eir_fire_brands", name="Fire-Brands", icon="onager", tier=1, siege=0.2, tough=8, stack=20, prov=6, cost=0.6, base="onager",
         innovation="innovation_eir_ringfort_craft", alt="tradition_eir_cattle_wealth", bonus={"tribal_holding": 0.15, "church_holding": 0.1},
         flavor="Teams of men with torches, pitch and bundles of thatch. The Irish annals burn a stronghold far more often than they storm one, and a burned timber hall or round tower is as good as a taken one."),
    dict(key="eir_wall_hook_crews", name="Wall-Hook and Ladder Crews", icon="mangonel", tier=2, siege=0.3, tough=14, stack=12, prov=12, cost=0.9, base="mangonel",
         innovation="innovation_eir_round_towers", alt="tradition_eir_culdee_christianity", bonus={"castle_holding": 0.1, "church_holding": 0.1},
         flavor="Long poles with iron hooks to pull down palisades and a hundred ladders for the rest. The Gauls tore down Caesar's works this way at Alesia, and the Welsh and Irish took many small forts the same way."),
    dict(key="eir_hide_rams", name="Hide-Covered Rams", icon="trebuchet", tier=3, siege=0.4, tough=20, stack=8, prov=12, cost=1.2, base="trebuchet",
         innovation="innovation_eir_gallowglass_hosting", alt="tradition_eir_tain_bo", bonus={"tribal_holding": 0.2, "castle_holding": 0.05},
         flavor="A ram-beam on a frame, roofed with wet cattle hides against fire and arrows. The Gauls and Britons learned it from Rome, and the Irish and Welsh kept it for the gate that would not burn."),
]


def build():
    L = Loc("eir_siege_l_english.yml")
    L.section("siege weapons")
    out = ["# Eire Reborn - siege weapons. Generated by tools/gen_siege.py\n\n"]
    vals = ["##########################################################################\n# Eire Reborn - siege weapon costs, generated by tools/gen_siege.py\n##########################################################################\n"]
    for u in UNITS:
        k = u["key"]
        bonus = "".join("\t\t%s = {\n\t\t\tsiege_value = %s\n\t\t}\n" % (h, v) for h, v in u["bonus"].items())
        out.append(f"""{k} = {{
	type = siege_weapon
	fights_in_main_phase = no

	damage = 0
	toughness = {u['tough']}

	siege_tier = {u['tier']}
	siege_value = {u['siege']}

	holding_bonus = {{
{bonus}	}}

	can_recruit = {{
		culture = {{
			OR = {{
				has_innovation = {u['innovation']}
				has_cultural_tradition = {u['alt']}
			}}
		}}
		NOT = {{ government_has_flag = government_is_in_steppe }}
	}}

	buy_cost = {{ gold = {k}_recruitment_cost }}
	low_maintenance_cost = {{ gold = {k}_low_maint_cost }}
	high_maintenance_cost = {{ gold = {k}_high_maint_cost }}
	provision_cost = {u['prov']}

	stack = {u['stack']}
	allowed_in_hired_troops = no
	icon = {u['icon']}
}}

""")
        for suffix, src in (("recruitment_cost", "recruitment_cost"), ("low_maint_cost", "low_maint_cost"), ("high_maint_cost", "high_maint_cost")):
            vals.append("%s_%s = {\n\tvalue = %s_%s\n\tmultiply = %s\n}\n" % (k, suffix, u["base"], src, u["cost"]))
        L.add(k, u["name"])
        L.add(k + "_flavor", "#F " + u["flavor"] + "#!")
    write("common/men_at_arms_types/eir_siege_types.txt", "".join(out))
    write("common/script_values/eir_siege_values.txt", "\n".join(vals))
    L.write()
    print("siege weapons written (%d)" % len(UNITS))


if __name__ == "__main__":
    build()
