def on_actions():
    out = ["##########################################################################",
           "# Eire Reborn - Update 3 on_actions (generated by tools/gen_script_conq.py)",
           "# Hooked into random_yearly_playable_pulse and the war-result lists in eir_on_actions.txt",
           "##########################################################################", ""]
    for c in CONQ:
        k = c["id"]
        prev = "" if k == 1 else "\t\thas_global_variable = eir_conq_done_%d\n" % (k - 1)
        out.append(f"""eir_conqueror_pulse_{k} = {{
	trigger = {{
		current_year >= {c['start']}
		NOT = {{ has_global_variable = eir_conq_done_{k} }}
{prev}		eir_conq_ready_trigger = yes
	}}
	random_events = {{
		chance_to_happen = 10
		1 = eir.06{k}0
	}}
}}
""")
    # war result hooks
    def hook(name, side):
        win = side == "defender"          # the defender won: the conqueror failed
        blk = [f"eir_war_won_{side}_conq = {{", "\teffect = {", "\t\tscope:attacker = {", "\t\t\tif = {", "\t\t\t\tlimit = { has_variable = eir_conq_id }",
               "\t\t\t\tsave_scope_as = eir_conqueror", "\t\t\t\tvar:eir_conq_title ?= { save_scope_as = eir_conq_title }",
               "\t\t\t\tscope:defender = {", "\t\t\t\t\tif = {", "\t\t\t\t\t\tlimit = { is_ai = no }", "\t\t\t\t\t\tsave_scope_as = eir_conq_player", "\t\t\t\t\t}",
               "\t\t\t\t\telse_if = {", "\t\t\t\t\t\tlimit = {", "\t\t\t\t\t\t\texists = top_liege", "\t\t\t\t\t\t\ttop_liege = { is_ai = no }", "\t\t\t\t\t\t}",
               "\t\t\t\t\t\ttop_liege = { save_scope_as = eir_conq_player }", "\t\t\t\t\t}", "\t\t\t\t}",
               "\t\t\t\tif = {", "\t\t\t\t\tlimit = { exists = scope:eir_conq_player }", "\t\t\t\t\tscope:eir_conq_player = {"]
        first = True
        for c in CONQ:
            k = c["id"]
            ev = 1 if win else 2
            blk += ["\t\t\t\t\t\t%s = {" % ("if" if first else "else_if"), "\t\t\t\t\t\t\tlimit = { scope:eir_conqueror.var:eir_conq_id = %d }" % k,
                    "\t\t\t\t\t\t\ttrigger_event = eir.06%d%d" % (k, ev), "\t\t\t\t\t\t}"]
            first = False
        blk += ["\t\t\t\t\t}", "\t\t\t\t}", "\t\t\t\telse = {", "\t\t\t\t\teir_conq_clear_effect = yes", "\t\t\t\t}", "\t\t\t\tremove_variable = eir_conq_id", "\t\t\t\tremove_variable = eir_conq_title", "\t\t\t}", "\t\t}", "\t}", "}", ""]
        return "\n".join(blk) + "\n"
    out.append(hook("a", "attacker"))
    out.append(hook("d", "defender"))
    return "\n".join(out)


def build():
    eff = EFFECTS_HEAD + ravage_effect()
    for c in CONQ:
        eff += pick_effect(c)
    write("common/scripted_effects/eir_effects_conq.txt", eff)
    write("common/scripted_triggers/eir_triggers_conq.txt", TRIGGERS)
    write("common/on_action/eir_on_actions_conq.txt", on_actions())
    print("script conq written")


if __name__ == "__main__":
    build()
