def ravage_effect():
    lines = ["# Downgrades the regional building chains of one province by a level (a ravaged province loses buildings).",
             "eir_ravage_province_effect = {", "\trandom = {", "\t\tchance = 60"]
    for fam in B.FAMILIES:
        key = fam[0]
        for levels, pat in ((4, "%s_%02d"), (2, "%s_t_%02d")):
            for lv in range(levels, 0, -1):
                k = pat % (key, lv)
                nxt = pat % (key, lv - 1)
                kw = "if" if lv == levels else "else_if"
                if lv == 1:
                    lines += ["\t\t%s = {" % kw, "\t\t\tlimit = { has_building = %s }" % k, "\t\t\tremove_building = %s" % k, "\t\t}"]
                else:
                    lines += ["\t\t%s = {" % kw, "\t\t\tlimit = { has_building = %s }" % k, "\t\t\tremove_building = %s" % k,
                              "\t\t\thidden_effect = { add_building = %s }" % nxt, "\t\t}"]
    lines += ["\t}", "}", ""]
    return "\n".join(lines) + "\n"


