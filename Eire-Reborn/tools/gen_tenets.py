"""Update 7 (Celtic tenets). Writes (all with BOM):
  common/religion/tenet_types/eir_tenets.txt       the fifteen tenets (faith AND personal), locked until their decision is taken
  common/scripted_triggers/eir_triggers_tenets.txt  eir_tn_<k>_trigger: the ruler's faith has the tenet, or he holds it personally
  localization/english/eir_tenets_l_english.yml"""
from eir_lib import *
from tenet_data import T, ORDER

COST = {"low": "faith_tenet_cost_low", "mid": "faith_tenet_cost_mid", "high": "faith_tenet_cost_high", "massive": "faith_tenet_cost_massive"}


def build():
    import dec_v13  # noqa: F401  (registers every decision, so the unlock names are known)
    from gen_decisions import DEC
    names = {d["key"]: d["name"] for d in DEC}
    L = Loc("eir_tenets_l_english.yml")
    out = ["# Eire Reborn - tenets. Generated by tools/gen_tenets.py\n"
           "# Each tenet works as a faith tenet (new faiths and reforms) and as a personal tenet. All fifteen stay hidden until a decision unlocks them.\n\n"]
    trig = ["# Eire Reborn - tenet triggers. Generated by tools/gen_tenets.py\n\n"]
    L.section("tenets")
    for k in ORDER:
        t = T[k]
        key = "tenet_eir_" + k
        var = "eir_tenet_" + k
        for sect in ("fmod", "cmod", "pmod"):
            check_keys(key, t[sect])
        fl, pf = t["fparams"][0][0], t["pflags"][0][0]
        virtues = "".join("\t\t\t%s = { weight = %d scale = %d }\n" % v for v in t["virtues"])
        sins = "".join("\t\t\t%s = { weight = %d scale = %d }\n" % v for v in t["sins"])
        out.append(f"""{key} = {{
	icon = {t['icon']}

	is_shown = {{
		custom_tooltip = {{
			text = {key}_locked_tt
			has_global_variable = {var}
		}}
	}}

	can_pick = {{
		custom_tooltip = {{
			text = {key}_locked_tt
			has_global_variable = {var}
		}}
	}}

	can_pick_as_personal_tenet = {{
		custom_tooltip = {{
			text = {key}_locked_tt
			has_global_variable = {var}
		}}
	}}

	piety_cost = {{
		value = {COST[t['cost']]}

		# Multiplier for keeping same tenet
		if = {{
			limit = {{ rite_has_tenet = {key} }}
			multiply = faith_unchanged_doctrine_cost_mult
		}}
	}}

	parameters = {{
		{fl}
	}}

	character_modifier = {{
{fields_block(t['fmod'], chr(9) * 2)}	}}

	county_modifier = {{
{fields_block(t['cmod'], chr(9) * 2)}	}}

	personal_tenet_modifier = {{
{fields_block(t['pmod'], chr(9) * 2)}	}}

	personal_tenet_parameters = {{
		{pf}
	}}

	traits = {{
		virtues = {{
{virtues}		}}
		sins = {{
{sins}		}}
	}}
}}

""")
        L.add(key + "_name", t["name"])
        L.add(key + "_desc", t["desc"])
        L.add(key + "_locked_tt", "Unlocked by the decision %s" % names[t["unlock"]])
        L.add("doctrine_parameter_" + fl, t["fparams"][0][1])
        L.add("doctrine_parameter_" + pf, t["pflags"][0][1])
        trig.append(f"""eir_tn_{k}_trigger = {{
	OR = {{
		has_personal_tenet_flag = {pf}
		rite ?= {{ rite_has_parameter = {fl} }}
	}}
}}

""")
    write("common/religion/tenet_types/eir_tenets.txt", "".join(out))
    write("common/scripted_triggers/eir_triggers_tenets.txt", "".join(trig))
    L.write()
    print("tenets written (%d)" % len(ORDER))


if __name__ == "__main__":
    build()
