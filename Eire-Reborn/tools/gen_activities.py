def tabs(text, n):
    return "".join(("\t" * n + ln + "\n") if ln.strip() else "\n" for ln in text.strip("\n").split("\n"))


def option_block(act, cat, opts, loc, costs=None):
    out = "\t\t%s = {\n" % cat
    for i, o in enumerate(opts):
        key = o[0]
        out += "\t\t\t%s = {\n" % key
        if i == 0:
            out += "\t\t\t\tdefault = yes\n"
        if costs and costs[i]:
            out += "\t\t\t\tcost = {\n\t\t\t\t\tgold = {\n\t\t\t\t\t\tadd = {\n\t\t\t\t\t\t\tvalue = %s\n\t\t\t\t\t\t\tdesc = %s\n\t\t\t\t\t\t}\n\t\t\t\t\t}\n\t\t\t\t}\n" % (costs[i], key)
        out += "\t\t\t\tai_will_do = {\n\t\t\t\t\tvalue = 10\n\t\t\t\t}\n"
        out += "\t\t\t}\n"
    return out + "\t\t}\n"


