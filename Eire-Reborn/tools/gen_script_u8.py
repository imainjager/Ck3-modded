"""Update 8: the small pulses for the court-position and faith events. Writes common/on_action/eir_on_actions_u8.txt
Hooked into random_yearly_playable_pulse in eir_on_actions.txt."""
from eir_lib import *

COURT = ["eir_ollamh", "eir_brehon", "eir_druid", "eir_foster_father"]


def build():
    cond = "".join("\t\t\temploys_court_position = %s_court_position\n" % p for p in COURT)
    court_events = "".join("\t\t1 = eir.%04d\n" % n for n in range(1001, 1013))
    faith_events = "".join("\t\t1 = eir.%04d\n" % n for n in range(1013, 1019))
    text = f"""##########################################################################
# Eire Reborn - Update 8 pulses, generated by tools/gen_script_u8.py
##########################################################################

# A player ruler with an Ollamh, a Brehon, a Druid or an Aite at court may see one of their stories.
eir_court_pulse = {{
	trigger = {{
		is_ai = no
		OR = {{
{cond}		}}
	}}
	random_events = {{
		chance_to_happen = 12
{court_events}	}}
}}

# A Druidic ruler, or one who has founded the Culdee Reform, may see a story of their faith.
eir_faith_pulse = {{
	trigger = {{
		is_ai = no
		OR = {{
			faith = faith:eir_druidic
			has_character_modifier = eir_culdee_reform_modifier
		}}
	}}
	random_events = {{
		chance_to_happen = 10
{faith_events}	}}
}}
"""
    write("common/on_action/eir_on_actions_u8.txt", text)
    print("script u8 written")


if __name__ == "__main__":
    build()
