def relay_entries(events, extra=""):
    out = ""
    for num, weight, cond in events:
        mod = ""
        if cond:
            mod = "\t\t\t\t\tmodifier = {\n\t\t\t\t\t\tfactor = 0\n\t\t\t\t\t\t%s\n\t\t\t\t\t}\n" % cond
        out += "\t\t\t\t%d = {\n%s\t\t\t\t\ttrigger_event = eir.%04d\n\t\t\t\t}\n" % (weight, mod, num)
    return out


