def england_counties():
    t = re.sub(r"#[^\n]*", "", open(GAME + r"\common\landed_titles\00_landed_titles.txt", encoding="utf-8-sig").read())
    stack, n = [], set()
    for m in re.finditer(r"\b([ekdcb]_[a-z0-9_\-']+)\s*=\s*\{|\{|\}", t):
        if m.group(1):
            stack.append(m.group(1))
            if m.group(1).startswith("c_") and "k_england" in stack:
                n.add(m.group(1))
        elif m.group(0) == "{":
            stack.append(None)
        elif stack:
            stack.pop()
    return len(n)


